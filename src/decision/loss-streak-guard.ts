// изменений в мартингейле и без занижения весов/порогов): ни один
// существующий фильтр не реагирует на РЕАЛЬНУЮ историю исходов сделок.
// signal-cooldown.ts (isSuppressedByCooldown / isSuppressedByChopGuard /
// isSuppressedBySameDirectionSerial) целиком завязан на цену/зону — он не
// подавит три убыточные сделки подряд, если они пришлись на три разные
// ценовые зоны/паттерна. signal-filters.ts (REGIME_GATE_*, HIGH_VOL_GATE_*)
// снижает вероятность отдельного плохого входа по индикаторам ДО того, как
// известен исход, но тоже ничего не знает о том, что случилось с
// предыдущими сделками. useDemoAccountStore ранее хранил legacy-поле
// `consecutiveLosses`, но оно нигде не читалось (только удалялось при
// миграции схемы) — реального счётчика серии не было нигде в пайплайне.
//
// Этот модуль — независимый, изолированно тестируемый предохранитель:
// после LOSS_STREAK_GATE_THRESHOLD подряд идущих РЕАЛЬНЫХ убытков требует,
// чтобы следующий сигнал был не слабее 'strong' (тот же порог силы, что
// уже применяет "Система мартингейла" — см. STRONG_SIGNAL_SCORE_THRESHOLD
// в signal-builder.ts и strongSignalsOnly в engine.ts), пока серию не
// прервёт выигрыш. Сам мартингейл (размер ставки/стадии) не трогается, и
// ни один вес/порог не занижается — только временно повышается требование
// к силе сигнала, симметрично уже существующему strongSignalsOnly.
//
// Сознательно НЕ содержит побочных эффектов и не хранит состояние сама:
// и живой путь (useDemoAccountStore.ts, счётчик currentLossStreak,
// зеркалируемый в DecisionEngine через useTickStore.ts — см. подписку
// lossStreakUnsub), и бэктест (backtest/simulator.ts) держат счётчик у
// СЕБЯ и вызывают одни и те же функции ниже над своей последовательностью
// исходов — вместо того чтобы каждый пересчитывал серийность по-своему
// (тот же класс риска рассинхронизации, что уже чинился для псевдо-HTF и
// для R-модели бэктеста, см. docs/changelog/CHANGES_APPLIED_LOSS_STREAK_AUDIT_20260906.md
// и CHANGES_APPLIED_BACKTEST_PAYOUT_ECONOMICS_20260913.md).

/**
 * Сколько подряд идущих реальных убытков требуется, чтобы временно поднять
 * требование к силе сигнала до 'strong'. Порог сознательно небольшой (2) —
 * задача этого гейта не "поймать" уже случившуюся серию из 3, а не
 * допустить именно 3-ю сделку в серии, среагировав уже после 2-й.
 */
export const LOSS_STREAK_GATE_THRESHOLD = 2;

/**
 * Только РЕШЁННЫЕ исходы. 'tie' (демо-счёт) / 'timeout' (бэктест) /
 * 'pending' сюда намеренно не входят — они не продолжают и не прерывают
 * серию (как и в winRate/калибровке в остальном проекте, см.
 * useDemoAccountStore.ts::pnlToSignalOutcome и engine.ts::recordOutcome).
 * Вызывающий код обязан отфильтровать их до вызова nextLossStreak — эта
 * функция намеренно не принимает более широкий тип, чтобы такой фильтр
 * нельзя было случайно забыть.
 */
export type DecidedOutcome = 'win' | 'loss';

/**
 * Обновляет счётчик подряд идущих убытков по ОДНОМУ новому решённому
 * исходу: 'loss' увеличивает счётчик на 1, 'win' сбрасывает его в 0.
 * Чистая функция без побочных эффектов — вызывающий код (стор/бэктест)
 * хранит возвращаемое значение как собственное состояние и вызывает эту
 * функцию последовательно, в хронологическом порядке исходов.
 */
export function nextLossStreak(currentStreak: number, outcome: DecidedOutcome): number {
  return outcome === 'loss' ? currentStreak + 1 : 0;
}

/**
 * true, если текущая серия подряд идущих реальных убытков достигла порога
 * — следующий сигнал должен требовать strength === 'strong', а не
 * проходить по обычному scoreThreshold.
 */
export function requiresStrongOnlyForLossStreak(
  currentStreak: number,
  threshold: number = LOSS_STREAK_GATE_THRESHOLD,
): boolean {
  return currentStreak >= threshold;
}
