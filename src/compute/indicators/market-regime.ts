import type { Candle, MarketRegime } from '@/types/domain';
import { lastNonNull } from './helpers';
import { atr } from './atr';

// BUGFIX (аудит 2026-09-12, §5.1): OLS-регрессия по ВСЕМ точкам окна вместо
// разницы двух крайних точек (recent[0]/recent[period-1]). Возвращает
// per-bar наклон и intercept линии, ближайшей по МНК ко всей серии —
// используется и для slope (§5.1), и как база для детрендинга при расчёте
// волатильности (§5.2), см. ниже.
function linearFit(values: number[]): { slope: number; intercept: number } {
  const n = values.length;
  if (n < 2) return { slope: 0, intercept: values[0] ?? 0 };
  const xMean = (n - 1) / 2;
  const yMean = values.reduce((a, b) => a + b, 0) / n;
  let num = 0;
  let den = 0;
  for (let i = 0; i < n; i++) {
    const dx = i - xMean;
    num += dx * (values[i] - yMean);
    den += dx * dx;
  }
  const slope = den > 0 ? num / den : 0;
  const intercept = yMean - slope * xMean;
  return { slope, intercept };
}

export function detectMarketRegime(candles: Candle[], period: number = 20, atrPeriod: number = 14): MarketRegime {
  if (candles.length < period + 5) return 'range';

  const closes = candles.map((c) => c.close);
  const recent = closes.slice(-period);

  const atrArr = atr(candles, atrPeriod);
  const atrValue = lastNonNull(atrArr);
  if (atrValue === null || atrValue <= 0) return 'range';

  // BUGFIX (аудит 2026-09-12, п.2 "порог 'тренд' не нормализован по
  // волатильности"): раньше здесь стоял сырой процентный порог 0.02 (2%
  // движения цены за `period` баров), никак не связанный с волатильностью
  // инструмента — тот же класс бага, что уже чинили для гистограммы MACD и
  // для калибровочной модели (насыщение/поломка на инструментах с сильно
  // разными масштабами цены и волатильности). На форексе 2% за 20 M1-баров
  // почти никогда не случается — `regime` там практически никогда не
  // становился 'trend'; на волатильной крипте это, наоборот, рутинно
  // случается даже внутри флэта. Именно эта неправильная классификация,
  // судя по всему, и была первопричиной симптома "ADX высокий, а
  // regime='range'", который signal-filters.ts (REGIME_GATE_*) до этого
  // патчил на уровне гейта, а не у источника.
  //
  // Суммарное перемещение цены за `period` баров нормализуется тем же ATR,
  // что и normalizedVol ниже — в единицах "во сколько раз накопленное
  // движение превышает ожидаемый разброс случайного блуждания при данной
  // волатильности" (ATR как оценка шага за бар, sqrt(period) — масштаб
  // случайного блуждания за period шагов).
  //
  // BUGFIX (аудит 2026-09-12, §5.1 "slopeAtr — эндпоинтная чувствительность
  // к шуму"): totalMove раньше считался как recent[last] - recent[0] — то
  // есть только по ДВУМ крайним точкам 20-барного окна. Один-единственный
  // шумовой выброс ровно на границе окна (recent[0] или последняя цена)
  // мог переключить весь режим trend↔range без реального изменения тренда
  // рынка. Теперь используется наклон OLS-регрессии по ВСЕМ point'ам окна
  // (linearFit выше), экстраполированный на всю ширину окна — тот же
  // смысл ("накопленное направленное движение"), но устойчивый к шуму на
  // одной паре точек, а не только к ней одной чувствительный.
  const { slope, intercept } = linearFit(recent);
  const totalMove = slope * (recent.length - 1);
  const slopeAtr = totalMove / (atrValue * Math.sqrt(period));
  if (Math.abs(slopeAtr) > 1.5) return 'trend';

  // BUGFIX (аудит 2026-09-12, §5.2 "normalizedVol смешивает волатильность с
  // направленным дрейфом"): раньше stdDev считался от сырых уровней цены
  // (recent) вокруг их простого среднего — у рынка, устойчиво идущего в
  // одну сторону (даже гладко, без шума в бытовом смысле), это стандартное
  // отклонение растёт почти линейно с пройденным расстоянием — артефакт
  // тренда, а не мера волатильности. Проверка slopeAtr выше частично
  // защищает от путаницы для сильных трендов, но оставляет зону: пологий,
  // но устойчивый тренд, не дотянувший до порога 1.5 по slopeAtr, мог тем
  // не менее дать высокий normalizedVol исключительно за счёт дрейфа и
  // ошибочно классифицироваться 'high-volatility' вместо 'trend'/'range'.
  // Теперь используется std ОСТАТКОВ после вычитания той же линии тренда
  // (linearFit выше) — направленный дрейф вычтен, остаётся только
  // разброс вокруг тренда, что и есть корректная мера волатильности для
  // этой цели.
  let residualSumSq = 0;
  for (let i = 0; i < recent.length; i++) {
    const fitted = intercept + slope * i;
    residualSumSq += Math.pow(recent[i] - fitted, 2);
  }
  const residualStdDev = Math.sqrt(residualSumSq / recent.length);

  // ПРИМЕЧАНИЕ (аудит 2026-09-12, §5.3): ATR (средний внутрибарный размах,
  // Wilder true range) остаётся нормировщиком и для slopeAtr, и для
  // normalizedVol. Аудит отдельно отмечает как открытый архитектурный
  // вопрос: отношение "внутрибарный размах / std доходности закрытий"
  // систематически отличается между классами инструментов (у крипто с
  // длинными фитилями это отношение обычно выше, чем у форекс на M1),
  // то есть один и тот же порог 1.5 по факту соответствует разным уровням
  // "истинной" трендовой силы на форекс и на крипто. Замена знаменателя на
  // std(returns) вместо ATR — не сделана здесь сознательно: это отдельное
  // архитектурное решение, требующее эмпирической проверки на реальной
  // истории форекс/крипто раздельно (см. Аудит.docx §5.3/§5.4/§7), а не
  // то, что можно корректно решить чтением кода в этой сессии (нет доступа
  // к npm run backtest — см. §0 отчёта). Числовой порог 1.5 по той же
  // причине не менялся.
  const normalizedVol = residualStdDev / atrValue;
  if (normalizedVol > 1.5) return 'high-volatility';

  return 'range';
}
