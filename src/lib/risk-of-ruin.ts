// РЕФАКТОРИНГ (бинарные опционы, Фаза 5 — "Мартингейл оставить как
// нативную механику, но провести risk-of-ruin аудит на ЭМПИРИЧЕСКОЙ (не
// предполагаемой) точности из Фазы 2"): раньше в приложении не было
// никакого расчёта риска мартингейла вообще — пользователь видел только
// переключатель "Система мартингейла: вкл/выкл" и текстовое описание
// стадий (см. SettingsPanel.tsx), без единой цифры о том, насколько это
// рискованно при РЕАЛЬНОЙ, а не воображаемой, точности сигналов.
//
// Система мартингейла в этом приложении (useDemoAccountStore.ts) — НЕ
// классический неограниченный мартингейл: ровно 3 стадии эскалации ставки
// (1→2→3) поверх stage0Amount, итого 4 попытки подряд. Проигрыш на стадии
// 3 сбрасывает серию на stage 0 (resolveTrade(): `trade.stage >= 3 →
// seriesReset: 'loss_final_stage'`) — то есть "риск разорения" здесь
// корректно определяется не как классическое разорение (баланс уходит в
// 0), а как вероятность потерять ВСЮ эскалированную сумму одного полного
// цикла (все 4 ставки подряд) — это и есть то, что нужно знать
// пользователю перед тем, как включать эскалацию ставки.
//
// probability = (1 - accuracy) ^ numberOfStages — accuracy ДОЛЖНА быть
// эмпирической (winRate по факту резолвнутых демо-сделок текущего
// инструмента/таймфрейма — см. useAnalyticsStore.winRate), а не
// предполагаемым числом типа 50% или "как у брокера в рекламе" — именно
// это и было явным требованием Фазы 5, отличающим правильный аудит от
// неправильного.

/** Число попыток в одном цикле мартингейла этого приложения: stage0 + 3 эскалации. */
export const MARTINGALE_STAGES_PER_CYCLE = 4;

/**
 * Вероятность N проигрышей подряд при данной точности направления
 * (accuracy = вероятность выигрыша ОДНОЙ сделки). Проигрыши считаются
 * независимыми последовательными испытаниями — упрощение (реальные сделки
 * могут быть слабо автокоррелированы через режим волатильности, см.
 * signal-filters.ts::HIGH_VOL_GATE_*), но это стандартное и консервативное
 * приближение для риск-оценки данного рода (недооценивать риск в эту
 * сторону не с чем — автокорреляция обычно УВЕЛИЧИВАЕТ вероятность
 * кластеризации убытков, то есть настоящий риск, скорее всего, не ниже
 * этой оценки).
 */
export function probabilityOfNConsecutiveLosses(accuracy: number, n: number): number {
  const clampedAccuracy = Math.max(0, Math.min(1, accuracy));
  return Math.pow(1 - clampedAccuracy, n);
}

/**
 * Вероятность потерять ВСЕ 4 ставки одного цикла мартингейла этого
 * приложения (stage0 + stage1 + stage2 + stage3 подряд в минус) — главная
 * цифра risk-of-ruin аудита для этой конкретной, ограниченной 3 стадиями
 * реализации.
 */
export function martingaleFullCycleLossProbability(empiricalAccuracy: number): number {
  return probabilityOfNConsecutiveLosses(empiricalAccuracy, MARTINGALE_STAGES_PER_CYCLE);
}

/** Суммарная сумма, теряемая при полном цикле — stage0Amount + все 3 эскалации. */
export function martingaleFullCycleLossAmount(stage0Amount: number, stageAmounts: [number, number, number]): number {
  return stage0Amount + stageAmounts[0] + stageAmounts[1] + stageAmounts[2];
}
