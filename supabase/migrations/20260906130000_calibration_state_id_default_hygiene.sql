/*
# calibration_state.id: убираем общий дефолт-константу

## Overview

Аудит-ревью Этапа 1 (нюанс инфраструктурной безопасности): миграция
20260906120000_calibration_state_per_symbol.sql сделала `symbol_id`
первичным ключом и сняла PK со столбца `id`, но НЕ трогала его
DEFAULT — он остался равен фиксированной константе
'00000000-0000-0000-0000-000000000001' (унаследовано из исходной
singleton-схемы). Столбец `id` нигде не читается и не пишется клиентом
(saveCalibrationState/loadCalibrationStateFromDb работают только через
symbol_id — см. src/lib/signal-persistence.ts) — риска для данных нет,
но у ВСЕХ новых строк (EURUSD и т.д.) будет одинаковое, визуально
похожее на PK значение id, что вводит в заблуждение при просмотре
таблицы напрямую (Supabase Studio, психологически читается как "все
строки — один и тот же объект").

Меняем DEFAULT на `gen_random_uuid()` — встроенную в Postgres 13+
функцию (расширения не требуются) — чтобы новые строки получали
уникальный id, как и полагается столбцу с таким именем. Существующие
строки не трогаем (их id остаётся как есть — это чисто визуальная/
гигиеническая правка, не влияющая на работу приложения).

## What changes

1. `calibration_state.id` DEFAULT меняется с фиксированной константы на
   `gen_random_uuid()`.
2. Ничего не удаляется, не переименовывается, RLS/политики не
   затрагиваются — безопасно перезапускать.
*/

ALTER TABLE calibration_state
  ALTER COLUMN id SET DEFAULT gen_random_uuid();
