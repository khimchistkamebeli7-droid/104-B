/*
# calibration_state: добавляем feature_mean / feature_std

## Overview

БАГ (аудит "калибровка: 0 сигналов после 100", реальный инцидент): после
накопления MIN_SAMPLES=100 резолвнутых исходов калибровочная модель
(логистическая регрессия, src/decision/calibration-model.ts) обучалась
полным батч-градиентным спуском НА СЫРЫХ, ненормированных признаках —
среди них 'vwap' и 'atr' идут абсолютным значением цены инструмента (для
BTCUSDT vwap ~ 45000-120000), тогда как остальные признаки уже нормированы
в диапазон примерно [-1, 1]. Из-за этого перекоса масштаба градиент по
весам 'vwap'/'atr' взрывался за первые же эпохи, вес расходился на
порядки, и predict() после этого НАВСЕГДА (пока не переобучится на новых
данных) залипал на константе ~0 или ~1 для абсолютно любого входа —
gate `calibratedProbability < priorityThreshold` в signal-builder.ts либо
блокировал 100% новых сигналов (если залипание было в сторону 0), либо
переставал фильтровать вообще (если в сторону 1). Наблюдаемый симптом:
"после набора 100 сигналов для калибровки — полная остановка генерации
сигналов, 0 сигналов за 2 часа".

Фикс (src/decision/calibration-model.ts::trainLogisticRegression) —
z-score стандартизация признаков перед обучением: каждый признак
приводится к среднему 0 / стандартному отклонению 1 по обучающей выборке.
featureMean/featureStd, посчитанные при обучении, ОБЯЗАНЫ применяться к
входу и при каждом predict() — иначе уже обученные weights снова
разъедутся с интерпретацией входа. Эта миграция добавляет для них место
в Supabase, ровно тем же способом (per-symbol строка), каким уже хранятся
weights/bias/samples — см. `saveCalibrationState`/`loadCalibrationStateFromDb`
в src/lib/signal-persistence.ts.

## What changes

1. `feature_mean double precision[]` — NULLABLE. NULL для всех уже
   существующих строк (обучены до этого фикса, т.к. столбца не было) —
   клиент трактует NULL как "легаси-состояние, нормализации нет" и
   принудительно переобучает модель на уже накопленных (валидных!)
   samples при следующей загрузке (см. loadCalibrationStateFromDb + вызов
   triggerRetrain в useTickStore.ts::switchCalibrationModel — она уже
   безусловно переретрейнит при dbState.samples.length > 0, эта миграция
   лишь даёт клиенту куда положить результат такого переретрейна).
2. `feature_std double precision[]` — тот же принцип.
3. Оба столбца NULLABLE (не NOT NULL) сознательно — принудительный
   NOT NULL потребовал бы backfill'а для существующих строк, а
   единственное осмысленное значение backfill'а ("официально считаем,
   что нормализации не было") и так выражается через NULL естественным
   образом, без искусственного дефолта вроде массива нулей/единиц,
   который выглядел бы как настоящая (посчитанная) статистика.

## Important notes

- Ничего не удаляется и не теряется: существующие weights/bias/samples
  остаются как есть, просто READ-путь клиента переобучит их же на лету
  тем же алгоритмом, что и раньше (данные валидны — баг был только в
  обучении, не в сборе данных).
- Безопасно перезапускать (`ADD COLUMN IF NOT EXISTS`), как и остальные
  миграции в этом проекте.
- RLS/политики не меняются — они уже действуют на уровне таблицы
  (`TO anon, authenticated USING (true)`), новые столбцы наследуют их
  автоматически.
*/

ALTER TABLE calibration_state
  ADD COLUMN IF NOT EXISTS feature_mean double precision[];

ALTER TABLE calibration_state
  ADD COLUMN IF NOT EXISTS feature_std double precision[];
