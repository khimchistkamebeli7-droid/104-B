/*
  # Бинарные опционы: expiry_bars + удаление stop_loss/take_profit

  Часть рефакторинга "Вариант Б — бинарные опционы" (Фаза 0 + Фаза 1).

  ## Фаза 0 — баг рассинхронизации экспирации
  На карточке сигнала показывалась `recommended_expiry` (адаптивная,
  секунды), а фактический резолв исхода (outcome-scheduler.ts,
  useDemoAccountStore.ts, tick-store/outcomes.ts) везде был жёстко
  захардкожен на "ровно 1 бар после сигнала", независимо от того, что
  показывала карточка. `expiry_bars` — единственное число, которое теперь
  реально управляет резолвом во всех местах, вычисляется в
  decision/signal-builder.ts из того же `recommended_expiry`, который идёт
  на карточку — по построению не может с ним разойтись.

  Nullable: у уже существующих строк `expiry_bars` будет NULL — читающий
  код (`signal-persistence.ts::rowToSignal`, `outcome-scheduler.ts`,
  `useDemoAccountStore.ts`) трактует NULL как 1 бар, поскольку старые
  записи были фактически резолвлены именно так (это и есть баг, который
  чинит эта колонка) — не переписывает задним числом уже посчитанную
  статистику.

  ## Фаза 1 — "честный бинарный опцион"
  `stop_loss`/`take_profit` удаляются целиком, не переразмечаются:
  бинарный опцион с фиксированной экспирацией и фиксированной выплатой не
  торгует "на разницу до цели" — исход определяется только знаком движения
  цены (entry_price vs цена закрытия на expiry_bars-й свече). Хранить
  структурные SL/TP в БД после того, как ни один код их больше не
  вычисляет и не потребляет, означало бы держать заведомо неактуальные,
  вводящие в заблуждение данные в проде.

  ВНИМАНИЕ (порядок применения): эта миграция должна накатываться ПОСЛЕ
  деплоя кода из Фазы 0/1 (expiry_bars уже пишется, stop_loss/take_profit
  уже не пишутся) — иначе клиенты на старой версии кода получат ошибку
  NOT NULL при попытке INSERT без stop_loss/take_profit, а INSERT в
  expiry_bars от новых клиентов будет падать до появления колонки.
*/

ALTER TABLE trading_signals
  ADD COLUMN IF NOT EXISTS expiry_bars integer;

ALTER TABLE trading_signals
  DROP COLUMN IF EXISTS stop_loss,
  DROP COLUMN IF EXISTS take_profit;
